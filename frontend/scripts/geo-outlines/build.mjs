// Builds the Geo Map outlines assets: Natural Earth 50m admin-0 countries, and
// 10m admin-1 states/provinces for every country with at least two of them.
// Run by hand when bumping Natural Earth or editing regions/aliases; the output is committed.
// Usage: pnpm build:geo-outlines
//
// Nothing is written until every invariant in validate.mjs holds. The assets
// are built in a staging folder and swapped in whole, so a failed run leaves
// the committed ones as they were.
import {
	existsSync,
	mkdirSync,
	readdirSync,
	renameSync,
	rmSync,
	writeFileSync,
} from 'node:fs';
import { join } from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
import { gzipSync } from 'node:zlib';

import {
	ASSETS_DIR,
	COUNTRIES_URL,
	SUBDIVISION_LIST_FILE,
	SUBDIVISIONS_URL,
} from './config.mjs';
import { buildCountries } from './countries.mjs';
import { buildSubdivisions } from './subdivisions.mjs';
import { validate } from './validate.mjs';

const DOWNLOAD_TIMEOUT_MS = 120_000;
const DOWNLOAD_ATTEMPTS = 3;

const STAGING_DIR = `${ASSETS_DIR}.staging`;
const PREVIOUS_DIR = `${ASSETS_DIR}.previous`;
// Everything in the assets folder is generated; anything else would be lost
// in the swap, so its presence stops the build.
const GENERATED_ENTRIES = new Set([
	'countries-50m.json',
	'lookups.json',
	'subdivisions',
]);

const kb = (bytes) => `${(bytes / 1024).toFixed(0)} KB`;
const sizeOf = (json) =>
	`${kb(Buffer.byteLength(json))} raw / ${kb(gzipSync(json).length)} gzip`;

async function downloadFeatures(url) {
	for (let attempt = 1; ; attempt += 1) {
		try {
			const response = await fetch(url, {
				signal: AbortSignal.timeout(DOWNLOAD_TIMEOUT_MS),
			});
			if (!response.ok) {
				throw new Error(`HTTP ${response.status}`);
			}
			const body = await response.json();
			if (
				body?.type !== 'FeatureCollection' ||
				!Array.isArray(body.features) ||
				body.features.length === 0
			) {
				throw new Error('response is not a non-empty GeoJSON FeatureCollection');
			}
			return body;
		} catch (error) {
			if (attempt === DOWNLOAD_ATTEMPTS) {
				throw new Error(
					`download failed after ${attempt} attempts: ${url}\n  ${error.message}`,
				);
			}
			await sleep(attempt * 2_000);
		}
	}
}

function subdivisionListSource(countries) {
	return `// Generated by scripts/geo-outlines/build.mjs; do not edit.
export const SUBDIVISION_COUNTRY_CODES = [
${countries.map((country) => `\t'${country}',`).join('\n')}
] as const;
`;
}

// A run that died mid-swap leaves the assets in the previous folder.
function recoverInterruptedSwap() {
	if (!existsSync(ASSETS_DIR) && existsSync(PREVIOUS_DIR)) {
		renameSync(PREVIOUS_DIR, ASSETS_DIR);
	}
	rmSync(STAGING_DIR, { recursive: true, force: true });
	rmSync(PREVIOUS_DIR, { recursive: true, force: true });
}

function assertOnlyGeneratedEntries() {
	if (!existsSync(ASSETS_DIR)) {
		return;
	}
	const foreign = readdirSync(ASSETS_DIR).filter(
		(entry) => !GENERATED_ENTRIES.has(entry),
	);
	if (foreign.length > 0) {
		throw new Error(
			`${ASSETS_DIR} holds files this build doesn't generate: ${foreign.join(', ')}`,
		);
	}
}

/** Writes every output under the staging folder; returns the sizes report. */
function stage(outputs) {
	const subdivisionDir = join(STAGING_DIR, 'subdivisions');
	mkdirSync(subdivisionDir, { recursive: true });
	writeFileSync(join(STAGING_DIR, 'countries-50m.json'), outputs.countriesJson);
	writeFileSync(join(STAGING_DIR, 'lookups.json'), outputs.lookupsJson);
	const sizes = [];
	for (const [country, file] of outputs.subdivisionFiles) {
		const json = JSON.stringify(file);
		writeFileSync(join(subdivisionDir, `${country}.json`), json);
		sizes.push({
			country,
			shapes: file.objects.subdivisions.geometries.length,
			gzip: gzipSync(json).length,
		});
	}
	writeFileSync(`${SUBDIVISION_LIST_FILE}.staging`, outputs.subdivisionList);
	return sizes;
}

/** Swaps the staged assets in; puts the previous ones back if that fails. */
function commitStaged() {
	const hadAssets = existsSync(ASSETS_DIR);
	if (hadAssets) {
		renameSync(ASSETS_DIR, PREVIOUS_DIR);
	}
	try {
		renameSync(STAGING_DIR, ASSETS_DIR);
	} catch (error) {
		if (hadAssets) {
			renameSync(PREVIOUS_DIR, ASSETS_DIR);
		}
		throw error;
	}
	renameSync(`${SUBDIVISION_LIST_FILE}.staging`, SUBDIVISION_LIST_FILE);
	rmSync(PREVIOUS_DIR, { recursive: true, force: true });
}

function cleanUpStaging() {
	rmSync(STAGING_DIR, { recursive: true, force: true });
	rmSync(`${SUBDIVISION_LIST_FILE}.staging`, { force: true });
}

function report(countries, subdivisions, outputs, sizes) {
	const totalGzip = sizes.reduce((sum, { gzip }) => sum + gzip, 0);
	return {
		countries: {
			...countries.report,
			sizes: {
				'countries-50m.json': sizeOf(outputs.countriesJson),
				'lookups.json': sizeOf(outputs.lookupsJson),
			},
		},
		subdivisions: {
			...subdivisions.report,
			countries: sizes.length,
			totalGzip: kb(totalGzip),
			largest: [...sizes]
				.sort((a, b) => b.gzip - a.gzip)
				.slice(0, 10)
				.map(
					({ country, shapes, gzip }) =>
						`${country}: ${shapes} shapes, ${kb(gzip)} gzip`,
				),
		},
	};
}

async function main() {
	recoverInterruptedSwap();
	assertOnlyGeneratedEntries();

	const [countrySource, subdivisionSource] = await Promise.all([
		downloadFeatures(COUNTRIES_URL),
		downloadFeatures(SUBDIVISIONS_URL),
	]);
	const countries = buildCountries(countrySource);
	const subdivisions = buildSubdivisions(subdivisionSource);
	validate(countries, subdivisions);

	const outputs = {
		countriesJson: JSON.stringify(countries.topology),
		lookupsJson: JSON.stringify(countries.lookups),
		subdivisionFiles: subdivisions.files,
		subdivisionList: subdivisionListSource([...subdivisions.files.keys()]),
	};
	try {
		const sizes = stage(outputs);
		commitStaged();
		process.stdout.write(
			`${JSON.stringify(report(countries, subdivisions, outputs, sizes), null, 2)}\n`,
		);
	} finally {
		cleanUpStaging();
	}
}

main().catch((error) => {
	process.stderr.write(`Geo outlines build failed: ${error.message}\n`);
	process.exitCode = 1;
});
