import hashlib
import io
import sys
import urllib.request
import zipfile
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

RELEASE_URL = "https://github.com/rsms/inter/releases/download/v4.1/Inter-4.1.zip"
RELEASE_SHA256 = "9883fdd4a49d4fb66bd8177ba6625ef9a64aa45899767dde3d36aa425756b11e"
OUT_DIR = Path(__file__).resolve().parent.parent / "src/assets/fonts/inter"
STYLES = {"normal": "InterVariable", "italic": "InterVariable-Italic"}

# Google Fonts' latin range plus the symbols the UI renders.
CORE_RANGES = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,"
    "U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,"
    "U+FEFF,U+FFFD,U+03A9,U+03BC,U+2190-21FF,U+2264-2265,U+221E,U+2248,"
    "U+2260,U+2318,U+2713,U+2717,U+23CE"
)


def parse_ranges(ranges: str) -> set[int]:
    codepoints = set()
    for part in ranges.split(","):
        start, _, end = part.strip().removeprefix("U+").partition("-")
        codepoints.update(range(int(start, 16), int(end or start, 16) + 1))
    return codepoints


def format_ranges(codepoints: set[int], others: set[int]) -> str:
    """Collapses codepoints into ranges, bridging short gaps that hold none of `others`.

    A long bridge would make text in scripts Inter lacks, such as CJK or emoji,
    download a file with nothing for it.
    """
    ranges = []
    for cp in sorted(codepoints):
        gap = range(ranges[-1][1] + 1, cp) if ranges else None
        if gap is not None and len(gap) <= 32 and not any(c in others for c in gap):
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ", ".join(
        f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in ranges
    )


def read_release(path: str | None) -> zipfile.ZipFile:
    data = (
        Path(path).read_bytes() if path else urllib.request.urlopen(RELEASE_URL).read()
    )
    if hashlib.sha256(data).hexdigest() != RELEASE_SHA256:
        sys.exit("Inter release does not match RELEASE_SHA256")
    return zipfile.ZipFile(io.BytesIO(data))


def write_subset(font: TTFont, codepoints: set[int], path: Path) -> None:
    options = subset.Options()
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.hinting = False
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = "woff2"
    font.save(path)


def main() -> None:
    release = read_release(sys.argv[1] if len(sys.argv) > 1 else None)
    core = parse_ranges(CORE_RANGES)
    faces = []

    for style, name in STYLES.items():
        source = io.BytesIO(release.read(f"web/{name}.woff2"))
        pinned = io.BytesIO()
        # `font-optical-sizing: none` renders every size at the default opsz.
        instancer.instantiateVariableFont(TTFont(source), {"opsz": 14}).save(pinned)
        available = set(TTFont(pinned).getBestCmap())
        parts = {"latin": available & core, "rest": available - core}

        # The latin face comes last so it wins wherever the two ranges meet.
        for part in ("rest", "latin"):
            filename = f"{name}-{part}.woff2"
            pinned.seek(0)
            write_subset(TTFont(pinned), parts[part], OUT_DIR / filename)
            other = parts["rest" if part == "latin" else "latin"]
            faces.append(
                "@font-face {\n"
                "\tfont-family: 'Inter';\n"
                f"\tfont-style: {style};\n"
                "\tfont-weight: 100 900;\n"
                "\tfont-display: swap;\n"
                f"\tsrc: url('./{filename}') format('woff2');\n"
                f"\tunicode-range: {format_ranges(parts[part], other)};\n"
                "}\n"
            )

    (OUT_DIR / "_faces.scss").write_text(
        "// Generated by scripts/subset-inter.py.\n\n" + "\n".join(faces)
    )


if __name__ == "__main__":
    main()
